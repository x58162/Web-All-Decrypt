<?php

//==================================================
// sitemap.php
//
// XML Sitemap
//
// 功能：
// 1. 提供搜尋引擎網站地圖
// 2. 自動列出網站主要頁面
// 3. 列出四種彩種主要頁面
// 4. 自動產生 ticket_generator.php
//    4 彩種 × 2 資料方式 × 2 版型
//    = 16 個參數網址
// 5. 使用正式 HTTPS 網址
//
// 網站：
// https://all-decrypt.com
//
//==================================================


//==================================================
// 正式網站網址
//==================================================

$siteUrl =
    "https://all-decrypt.com";


//==================================================
// XML Header
//==================================================

header(
    "Content-Type: application/xml; charset=utf-8"
);


//==================================================
// XML 開始
//==================================================

echo '<?xml version="1.0" encoding="UTF-8"?>';

echo "\n";

echo '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">';

echo "\n";


//==================================================
// Sitemap 頁面資料
//
// 只放希望 Google 收錄的正式頁面
//==================================================

$pages =
[

    //==================================================
    // 首頁
    //==================================================

    [
        "url" =>
            "/",

        "changefreq" =>
            "daily",

        "priority" =>
            "1.0"
    ],


    //==================================================
    //==================================================
    // 高機率版路
    //==================================================
    //==================================================

    [
        "url" =>
            "/index.php?lottery=dailycash",

        "changefreq" =>
            "daily",

        "priority" =>
            "0.9"
    ],

    [
        "url" =>
            "/index.php?lottery=biglottery",

        "changefreq" =>
            "daily",

        "priority" =>
            "0.9"
    ],

    [
        "url" =>
            "/index.php?lottery=fantasy5",

        "changefreq" =>
            "daily",

        "priority" =>
            "0.9"
    ],

    [
        "url" =>
            "/index.php?lottery=marksix",

        "changefreq" =>
            "daily",

        "priority" =>
            "0.9"
    ],


    //==================================================
    //==================================================
    // 開獎結果
    //==================================================
    //==================================================

    [
        "url" =>
            "/dailycash.php?lottery=dailycash",

        "changefreq" =>
            "daily",

        "priority" =>
            "0.9"
    ],

    [
        "url" =>
            "/dailycash.php?lottery=biglottery",

        "changefreq" =>
            "daily",

        "priority" =>
            "0.9"
    ],

    [
        "url" =>
            "/dailycash.php?lottery=fantasy5",

        "changefreq" =>
            "daily",

        "priority" =>
            "0.9"
    ],

    [
        "url" =>
            "/dailycash.php?lottery=marksix",

        "changefreq" =>
            "daily",

        "priority" =>
            "0.9"
    ]

];


//==================================================
// ticket_generator.php
//
// 自動產生所有參數組合
//
// game：
// 539
// fantasy5
// biglottery
// marksix
//
// order：
// sorted
// drop
//
// layout：
// long
// four
//
// 4 × 2 × 2 = 16
//==================================================

$ticketGames =
[
    "539",
    "fantasy5",
    "biglottery",
    "marksix"
];


$ticketOrders =
[
    "sorted",
    "drop"
];


$ticketLayouts =
[
    "long",
    "four"
];


//==================================================
// 自動產生 16 個 ticket_generator.php 網址
//==================================================

foreach (
    $ticketGames
    as $ticketGame
) {

    foreach (
        $ticketOrders
        as $ticketOrder
    ) {

        foreach (
            $ticketLayouts
            as $ticketLayout
        ) {

            //--------------------------------------------------
            // 建立查詢參數
            //--------------------------------------------------

            $query =
                http_build_query(
                    [
                        "game" =>
                            $ticketGame,

                        "order" =>
                            $ticketOrder,

                        "layout" =>
                            $ticketLayout
                    ],
                    "",
                    "&",
                    PHP_QUERY_RFC3986
                );


            //--------------------------------------------------
            // 加入 Sitemap
            //--------------------------------------------------

            $pages[] =
            [
                "url" =>
                    "/ticket_generator.php?" .
                    $query,

                "changefreq" =>
                    "daily",

                "priority" =>
                    "0.8"
            ];
        }
    }
}


//==================================================
// 輸出 Sitemap
//==================================================

foreach (
    $pages
    as $page
) {

    //--------------------------------------------------
    // 防止資料錯誤
    //--------------------------------------------------

    if (
        !isset(
            $page["url"]
        )
    ) {

        continue;
    }


    //--------------------------------------------------
    // 完整網址
    //--------------------------------------------------

    $url =
        $siteUrl .
        $page["url"];


    //--------------------------------------------------
    // URL 開始
    //--------------------------------------------------

    echo "    <url>\n";


    //--------------------------------------------------
    // loc
    //--------------------------------------------------

    echo "        <loc>" .
        htmlspecialchars(
            $url,
            ENT_XML1,
            "UTF-8"
        ) .
        "</loc>\n";


    //--------------------------------------------------
    // changefreq
    //--------------------------------------------------

    if (
        isset(
            $page["changefreq"]
        )
    ) {

        echo "        <changefreq>" .
            htmlspecialchars(
                $page["changefreq"],
                ENT_XML1,
                "UTF-8"
            ) .
            "</changefreq>\n";
    }


    //--------------------------------------------------
    // priority
    //--------------------------------------------------

    if (
        isset(
            $page["priority"]
        )
    ) {

        echo "        <priority>" .
            htmlspecialchars(
                $page["priority"],
                ENT_XML1,
                "UTF-8"
            ) .
            "</priority>\n";
    }


    //--------------------------------------------------
    // URL 結束
    //--------------------------------------------------

    echo "    </url>\n";
}


//==================================================
// Sitemap 結束
//==================================================

echo "</urlset>";

?>
